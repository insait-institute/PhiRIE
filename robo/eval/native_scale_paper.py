"""Compact native DEV/TEST paper sections from canonical table sources."""
import json
from pathlib import Path

LABELS={'REF_NATIVE':'REF','B0_FIXED_NATIVE':'B0: fixed','B1_FIXED_PRIORITY':'B1: priority','B2_EVIDENCE':'B2: evidence','B3_AGENT_NATIVE':'B3: agent','B4_ROOM_REPAIR_NATIVE':'B4: repair','BM_BUDGET_MATCHED_NATIVE':'BM: fixed order'}


def render_section(out,tables,*,require_complete=False,comparisons=None):
    out=Path(out);rows=tables['T2_manipulation']
    blocks={(r['cohort_id'],r['scope'],r['sensor_regime'],r['renderer'],r['execution_protocol'],r['split'],r['policy_id']) for r in rows}
    if len(blocks)!=1:raise ValueError('compact native paper section requires one declared block')
    block=next(iter(blocks))
    if block[1]!='L0_target_only' or block[4]!='primary_native' or block[5] not in ('DEV','development','TEST','test'):
        raise ValueError('compact paper section requires declared target-only native DEV or TEST')
    tier='TEST' if block[5] in ('TEST','test') else 'DEV'
    prefix='native_'+tier.lower()
    label='native-'+tier.lower()
    if require_complete and not all(r['complete'] for r in rows):
        raise ValueError('paper transfer requires every primary cohort outcome terminal')
    lookup={r['method']:r for r in rows}
    if len(lookup)!=len(rows) or 'REF_NATIVE' not in lookup:raise ValueError('native paper method roster invalid')
    table=[r'\begin{table}[t]',r'\centering\small',
      r'\caption{Native target-only '+tier+r' comparison. Coverage retains build failures and abstentions. Dashes denote incomplete outcomes; conditional success uses executed episodes.}',
      r'\label{tab:'+label+'}',r'\begin{tabular}{lrrr}',r'\toprule',
      r'Method & Exec./plan & Success/plan & Cond. SR \\',r'\midrule']
    for method in ('REF_NATIVE','B0_FIXED_NATIVE','B3_AGENT_NATIVE','B4_ROOM_REPAIR_NATIVE','BM_BUDGET_MATCHED_NATIVE'):
        if method not in lookup:continue
        r=lookup[method];success=f"{r['successes_observed']}/{r['planned']}" if r['complete'] else '--'
        conditional=f"{100*r['success_per_executed']:.1f}\\%" if r['success_per_executed'] is not None else '--'
        table.append(f"{LABELS[method]} & {r['executed']}/{r['planned']} & {success} & {conditional} \\\\")
    table += [r'\bottomrule',r'\end{tabular}',r'\end{table}']
    (out/(prefix+'_results.tex')).write_text('\n'.join(table)+'\n')
    ref=lookup['REF_NATIVE'];measured=sum(r['measured'] for r in rows);planned=sum(r['planned'] for r in rows)
    section=[r'% Generated by robo.eval.paper_pipeline; do not edit numeric values.',r'\subsection{Native Sim--Recon--Sim: A Target-Only '+tier+' Test}',
      r'\input{tables/'+prefix+'_results}',
      f"We attempt target reconstruction in each of {ref['instances']} frozen RoboCasa365~\\cite{{robocasa365}} instances across {ref['layouts']} layouts, "
      r'using posed ideal RGB-D observations. The robot, controller, cameras, policy checkpoint, reset bank, instructions and native horizons remain fixed. '
      r'The room and destination retain privileged native geometry; the reconstructed target uses a uniform material. This isolates a complete target-asset intervention, not room reconstruction or Gaussian rendering.',
      f"Table~\\ref{{tab:{label}}} retains every planned reset; {measured}/{planned} units have terminal records in this immutable snapshot. "
      r'Build failure and abstention contribute zero service success while keeping native success unmeasured. Pending episodes do not become failures. '
      r'Native predicates retain their original contact/body-origin semantics; they do not certify whole-mesh containment or independently corresponding object frames.',
      r'B0 uses TRELLIS; B3 selects from TRELLIS/ReconViaGen proposals with a bounded registration retry. B4 uses measured contact, support, public-surface fit and destination-access evidence to choose bounded actions; BM uses the same action bank in fixed order. '
      r'Passing these construction checks is not independent physics validation. '+
      (r'These DEV observations do not establish TEST preservation, sim--real transfer, or a room-scale manipulation benefit.' if tier=='DEV' else
       r'The declared TEST block measures target-asset intervention under retained native context. It does not establish noninferiority or preservation, sim--real transfer, complete room construction, or a room-scale manipulation benefit.')]
    if all(k in lookup and lookup[k]['complete'] for k in ('B3_AGENT_NATIVE','B4_ROOM_REPAIR_NATIVE')):
        a,b=lookup['B3_AGENT_NATIVE'],lookup['B4_ROOM_REPAIR_NATIVE']
        if b['success_per_executed'] is not None and a['success_per_executed'] is not None and b['success_per_executed']>a['success_per_executed'] and b['success_per_planned']<a['success_per_planned']:
            section += [r'B4 raises conditional success but lowers success over all planned episodes relative to B3: stricter acceptance exposes a coverage penalty rather than an unconditional manipulation gain.']
    appearance=[r for r in tables.get('T1a_appearance',[]) if r['method'] in LABELS and (r.get('psnr') is not None or r.get('psnr_status')=='POSITIVE_INFINITY')]
    outputs={prefix+'_results.tex':'tables/'+prefix+'_results.tex',prefix+'_section.tex':'paper_sections/06_'+prefix+'.tex'}
    if appearance:
        art=[r'\begin{table}[t]',r'\centering\small',
          r'\caption{Native held-out full-frame appearance on common supported '+tier+r' instances ($n/N$); B1 is fixed priority and B2 evidence-only selection. Retained native background dominates image area; this is not object-only or Gaussian appearance.}',
          r'\label{tab:'+label+'-appearance}',r'\begin{tabular}{lrrrr}',r'\toprule',r'Method & $n/N$ & PSNR & SSIM & LPIPS \\',r'\midrule']
        for r in appearance:
            psnr=r'$\infty$' if r.get('psnr_status')=='POSITIVE_INFINITY' else f"{r['psnr']:.2f}"
            art.append(f"{LABELS[r['method']]} & {r['common_scenes']}/{r['scenes_planned']} & {psnr} & {r['ssim']:.4f} & {r['lpips']:.4f} \\\\")
        art += [r'\bottomrule',r'\end{tabular}',r'\end{table}']
        (out/(prefix+'_appearance.tex')).write_text('\n'.join(art)+'\n')
        section += [r'\ext{', r'\input{tables/'+prefix+'_appearance}',r'Table~\ref{tab:'+label+r'-appearance} uses predeclared held-out camera views at the frozen estimated object placement, with no evaluation alignment or exposure correction. '
                    r'PSNR, SSIM and LPIPS are conditional full-frame instance means on identical support. Only appearance units passing byte-exact native import controls contribute quality; failed controls, unavailable renders and missing constructions remain in the planned denominator.']
        if any(r.get('psnr_status')=='POSITIVE_INFINITY' for r in appearance):
            section += [r'An exact reconstructed/reference RGB match gives positive infinite PSNR; extended-real averaging preserves this value and includes every declared view.']
        section += [r'}', f"\\conf{{The held-out full-frame appearance comparison covers {appearance[0]['common_scenes']}/{appearance[0]['scenes_planned']} planned instances. Retained native background dominates the images; detailed standard metrics remain in the extended report and generated sources.}}"]
        outputs[prefix+'_appearance.tex']='tables/'+prefix+'_appearance.tex'
    if tier=='TEST':
        if not all(r['complete'] for r in rows):
            section.insert(2,r'\textbf{Incomplete TEST snapshot:} observed accounting only; incomplete-arm population rates and paired population conclusions remain unmeasured.')
        if all(r['complete'] for r in rows):
            paired=[]
            for conclusion in tables.get('test_conclusion_ledger',[]):
                if (conclusion.get('claim_id','').startswith('test_pair_') and conclusion.get('gate')=='PASS'
                    and conclusion.get('cohort_complete') is True and conclusion.get('enabled_sentence')):
                    sentence=conclusion['enabled_sentence']
                    for method in sorted(LABELS,key=len,reverse=True):sentence=sentence.replace(method,LABELS[method])
                    if '_' in sentence:raise ValueError('unrecognized method in generated paired conclusion')
                    paired.append(sentence.replace("%", r"\%"))
            if paired:section += [r'\ext{'+ ' '.join(paired)+r'}']
        section += [r'Coverage is reported before conditional quality. Shared-support geometry and available-method quality address different denominators; neither proves preserved manipulation. Separate fresh scope controls, development replay diagnostics and Gaussian engineering demonstrations are not pooled into this primary cohort.']
        section += [r'No feedback benefit, complete workspace or room replacement, or correct Gaussian robot occlusion follows from these native target-only results. A paired interval containing zero is not evidence of equivalence.']
        for audit in tables.get('native_import_adjudication_summary', []):
            if audit['method'] not in lookup or audit['split'].lower()!='test':
                raise ValueError('paper adjudication disclosure belongs to a different method/cohort')
            explanation=(r'The original watertight collision part has near-threshold local nonconvexity under the frozen explicit import check. '
                         if audit['all_watertight_near_threshold_nonconvex'] else r'The original collision asset fails the frozen explicit import check. ')
            disclosure=(f"An independent audit reclassifies {audit['classified_units']} prepolicy {LABELS[audit['method']]} import failures across {audit['affected_instances']} instance(s) "
                        r'from generic \texttt{CODE\_FAILED} to \texttt{BUILD\_FAILED}. '+explanation+
                        r'The original collision geometry, thresholds and native-success values remain unchanged; these units have no native success measurement. ')
            if audit['producer_accepted_objects'] is not None:
                disclosure+=(f"Producer acceptance covers {audit['producer_accepted_objects']} assets, while {audit['native_executed_instances']} instances have native execution; artifact production is distinct from native import validity.")
            section.append(disclosure)
        scope_outputs, scope_text = render_scope(out, tables, require_complete=require_complete)
        outputs.update(scope_outputs)
        section.extend(scope_text)
        gates=[dict(claim_id=key,scientific_gate='NOT_RUN',enabled_sentence='',disabled_sentence=sentence,required_gate=required)
               for key,sentence,required in DISABLED_CLAIMS]
        (out/'native_paper_claim_gates.json').write_text(json.dumps(gates,indent=2)+'\n')
    if tier=='TEST' and all(r['complete'] for r in rows):
        compact=compact_test_text(tables,comparisons or [])
        section=section[:3]+[r'\conf{'+compact+r'}',r'\ext{']+section[3:]+[r'}']
    (out/(prefix+'_section.tex')).write_text('\n\n'.join(section)+'\n')
    return outputs


DISABLED_CLAIMS = (
 ('preservation','SimAnyRoom preserves native manipulation capability.',
  'A prospectively declared preservation/noninferiority criterion and admissible complete paired evidence; nonsignificance is insufficient.'),
 ('full_room','SimAnyRoom reconstructs complete rooms while preserving manipulation.',
  'Complete declared room scope, retained-context disclosure and independent native outcomes; target-only or partial workspace evidence is insufficient.'),
 ('full_l2','Full workspace reconstruction retains task capability.',
  'Complete declared L2 scope and independent same-method fresh paired controls; partial role imports are insufficient.'),
 ('gs_occlusion','Gaussian observations preserve correct robot occlusion.',
  'Independent visibility validation and fresh native observer invariance; static/depth replay implementation checks are insufficient.'),
 ('feedback','Visual policy feedback compensates for reconstruction errors.',
  'Complete predeclared same-action versus same-policy diagnostic with matched horizon/reset and declared feedback effect; selected episodes are insufficient.'),
 ('sim_real','Native reconstruction transfers policy success to the physical world.',
  'Genuine matched physical trials with frozen policy, reset specification, observation and rubric.'),
)


def render_scope(out, tables, *, require_complete=False):
    """Format existing T4 estimates; keep fresh scope controls out of T2."""
    scopes = ('L0_target_only', 'L1_target_destination')
    methods = ('B3_AGENT_NATIVE', 'B4_ROOM_REPAIR_NATIVE')
    rows = [r for r in tables.get('T4_scope', []) if r.get('scope_run_id')]
    if not rows:
        return {}, []  # Legacy releases with no measured scope source.
    controls = tables.get('T4_native_controls', [])
    comparisons = tables.get('T4_scope_comparisons', [])
    index = {(r['method'], r['scope']): r for r in rows}
    if len(index) != len(rows) or set(index) != {(m, s) for m in methods for s in scopes}:
        raise ValueError('compact TEST scope requires exactly B3/B4 x L0/L1')
    fields = ('scope_run_id', 'cohort_id', 'policy_id', 'sensor_regime', 'renderer', 'execution_protocol', 'instances', 'layouts', 'planned')
    blocks = {tuple(r[k] for k in fields) for r in rows + controls}
    if len(blocks) != 1 or any(r['split'].lower() != 'test' for r in rows + controls):
        raise ValueError('scope paper source mixes fresh scope populations')
    if len(controls) != 1 or controls[0]['method'] != 'REF_NATIVE' or controls[0]['scope'] != scopes[0]:
        raise ValueError('scope paper requires its separate fresh native control')
    paired = {r['method']: r for r in comparisons}
    if len(paired) != len(comparisons) or set(paired) != set(methods):
        raise ValueError('scope paper paired estimates are missing or duplicated')
    for method, row in paired.items():
        base = index[(method, scopes[0])]
        if (row['scope_run_id'] != base['scope_run_id'] or row['baseline_scope'] != scopes[0]
            or row['scope'] != scopes[1] or row['planned_pairs'] != base['planned']):
            raise ValueError('scope pair does not bind the same fresh control population')
    complete = all(r['complete'] and r['unmeasured'] == 0 and r['measured'] == r['planned'] for r in rows + controls)
    complete = complete and all(r['paired_population_complete'] for r in comparisons)
    if require_complete and not complete:
        raise ValueError('paper transfer requires every scope phase outcome terminal')
    def success(row):
        return f"{row['successes_observed']}/{row['planned']}" if row['complete'] else '--'
    table = [r'\begin{table}[t]', r'\centering\small',
        r'\caption{Fresh within-method TEST scope comparison. L1 preserves the corresponding L0 target and rebuilds the destination. Build failures and abstentions retain the planned denominator.}',
        r'\label{tab:native-test-scope}', r'\begin{tabular}{llrrr}', r'\toprule',
        r'Method & Scope & Exec./plan & Success/plan & Cond. SR \\', r'\midrule']
    for method in methods:
        for scope, label in zip(scopes, ('L0', 'L1')):
            row = index[(method, scope)]
            conditional = '--' if row['success_per_executed'] is None else f"{100*row['success_per_executed']:.1f}\\%"
            table.append(f"{LABELS[method]} & {label} & {row['executed']}/{row['planned']} & {success(row)} & {conditional} \\\\")
    table += [r'\bottomrule', r'\end{tabular}', r'\end{table}']
    Path(out, 'native_test_scope.tex').write_text('\n'.join(table)+'\n')
    ref = controls[0]
    text = [r'\paragraph{Destination scope.} '
        f"A separate fresh-control TEST phase covers {ref['instances']} instances across {ref['layouts']} layouts. "
        r'Within each method, L1 retains the corresponding L0 target artifact and adds direct destination geometry. '
        r'Native fixture frames, articulations, accessories and goal handles remain retained context; this is not complete fixture or workspace reconstruction. '
        r'These controls are separate from the primary cohort and are not pooled with it.']
    if not complete:
        text += [r'\textbf{Incomplete scope phase:} population rates and paired population conclusions remain unmeasured.']
    detail = [r'\ext{\input{tables/native_test_scope}',
        f"The fresh native control records {ref['executed']}/{ref['planned']} executed episodes and {success(ref)} successes over planned episodes. "]
    summary = []
    for method in methods:
        base, expanded = (index[(method, s)] for s in scopes)
        summary.append(f"{LABELS[method]} executes {base['executed']} to {expanded['executed']} of {base['planned']} planned episodes from L0 to L1, "
                       f"with success/planned {success(base)} to {success(expanded)}.")
        paired_row = paired[method]
        if complete:
            low, high = paired_row['ci95_pp']
            if paired_row['delta_pp'] is None or low is None or high is None:
                raise ValueError('complete scope comparison lacks its existing interval')
            detail.append(f"{LABELS[method]} has L1-minus-L0 instance-macro success difference {paired_row['delta_pp']:.2f} percentage points "
                          f"(descriptive paired hierarchical 95\\% interval [{low:.2f}, {high:.2f}]).")
        detail.append(f"{LABELS[method]} retains {expanded['inherited_target_nonexecution_observed']} inherited target nonexecutions "
                      f"and {expanded['additional_scope_nonexecution_observed']} additional scope construction nonexecutions.")
    text.append(' '.join(summary))
    detail += [r'Intervals use the existing layout--instance--reset paired bootstrap. Limited independent layout support and binding-specific native predicates do not establish preservation or whole-mesh goal containment.}',]
    text.extend(detail)
    return {'native_test_scope.tex': 'tables/native_test_scope.tex'}, text


def compact_test_text(tables, comparisons):
    """Conference-length account; full generated evidence remains extended."""
    arms={r['method']:r for r in tables['T2_manipulation']}
    ref=arms['REF_NATIVE']
    text=[f"Across {ref['instances']} frozen instances and {ref['layouts']} layouts, we reconstruct only the target from posed ideal RGB-D, "
          r'using uniform materials and retaining native room/destination context. Policy, robot, cameras, control, resets and horizons remain fixed. '
          r'Table~\ref{tab:native-test} counts build failures and abstentions against planned success; native success remains unmeasured for unexecuted units.',
          r'B0 is fixed TRELLIS; B3 adds shared TRELLIS/ReconViaGen selection and bounded registration retry. B4 verifies and repairs context; BM uses the same action bank in fixed order.']
    pairs=[r for r in comparisons if r['method']=='B3_AGENT_NATIVE' and r['reference']=='B0_FIXED_NATIVE']
    if len(pairs)>1:raise ValueError('compact B3 comparison is ambiguous')
    if pairs:
        pair=pairs[0]
        if not pair['paired_population_complete']:raise ValueError('compact conference result requires complete B3/B0 pairs')
        low,high=pair['ci95_pp']
        effect=(f"improves service success over B0 by {pair['delta_pp']:.2f}" if low>0 else f"has a B3-minus-B0 service-success difference of {pair['delta_pp']:.2f}")
        text.append(f"The B3 bundle {effect} percentage points "
                    rf"(paired hierarchical 95\% interval [{low:.2f}, {high:.2f}]); this does not isolate its components or control extra computation.")
    if 'B3_AGENT_NATIVE' in arms and 'B4_ROOM_REPAIR_NATIVE' in arms:
        a,b=arms['B3_AGENT_NATIVE'],arms['B4_ROOM_REPAIR_NATIVE']
        if (b.get('success_per_executed') is not None and a.get('success_per_executed') is not None
            and b['success_per_executed']>a['success_per_executed'] and b['success_per_planned']<a['success_per_planned']):
            text.append('B4 raises conditional success but lowers planned success: its stricter acceptance loses coverage.')
    for audit in tables.get('native_import_adjudication_summary',[]):
        label=audit['method'].split('_',1)[0]
        text.append(f"{audit['classified_units']} {label} prepolicy import failures were audited as construction failures; original geometry and native outcomes are unchanged.")
        if audit['producer_accepted_objects'] is not None:
            text.append(f"Producer acceptance covers {audit['producer_accepted_objects']} assets versus {audit['native_executed_instances']} instances with native execution.")
    scope={ (r['method'],r['scope']):r for r in tables.get('T4_scope',[]) if r.get('scope_run_id') }
    if scope and all(r["complete"] for r in scope.values()):
        first=next(iter(scope.values()))
        text.append(f"A separate fresh-control phase spans {first['instances']} instances and {first['layouts']} layouts. Adding destination reconstruction changes L0-to-L1 service successes "
                    +'; '.join(f"{m.split('_',1)[0]}: {scope[(m,'L0_target_only')]['successes_observed']}/{scope[(m,'L0_target_only')]['planned']} to {scope[(m,'L1_target_destination')]['successes_observed']}/{scope[(m,'L1_target_destination')]['planned']}" for m in ('B3_AGENT_NATIVE','B4_ROOM_REPAIR_NATIVE'))
                    +'. Native fixture articulations and goal handles remain.')
    appearance=[r for r in tables.get('T1a_appearance',[]) if r.get('common_scenes') is not None]
    if appearance:
        row=appearance[0]
        text.append(f"Full-frame appearance has common support {row['common_scenes']}/{row['scenes_planned']}; retained background dominates.")
    text.append('Binding-specific predicates do not certify whole-mesh containment. These tests do not establish preservation, feedback benefit or complete room construction. Detailed protocols, intervals and failure audits remain in the extended report.')
    return '\n\n'.join(text)
