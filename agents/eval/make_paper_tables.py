"""Generate the paper's data tables as LaTeX from the on-disk results.

Every number in docs/paper/tables/*.tex comes from this script, so the paper can be
regenerated from the outputs tree and never drifts from the measurements.

Usage:  python -m agents.eval.make_paper_tables [--out docs/paper/tables]

Reads:
  outputs/val_summary.json                  aggregate + per-scene (GT-driven)
  outputs/<scene>_factory/report.json       per-object tiers / F1 / drop test
  outputs/<scene>_factory/objects/hybrid_all.json   per-object TRELLIS vs RVG
"""
from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

import numpy as np

from agents.core import common as C

# Categories are reported at alias-resolved granularity; these aliases refer to
# the same physical category and are merged for the per-category table.
ALIAS = {
    "carboard box": "cardboard box", "storage box": "box", "tissue box": "box",
    "plastic bottle": "bottle", "glass bottle": "bottle",
    "water bottle": "bottle", "computer mouse": "mouse", "paper cup": "cup",
    "mug": "cup", "headphone": "headphones", "shoes": "shoe",
    "remote control": "remote", "flower pot": "plant pot", "phone": "cellphone",
    "notebook": "book", "laptop charger": "charger",
}
MIN_CAT_N = 8   # categories with fewer instances are pooled into "other"


def esc(s: str) -> str:
    return s.replace("_", r"\_").replace("&", r"\&")


def load_scene_objects(root: Path):
    """-> list of per-object dicts across every factory scene with a report."""
    rows = []
    for rep in sorted(root.glob("*_factory/report.json")):
        scene = rep.parent.name.replace("_factory", "")
        try:
            data = json.loads(rep.read_text())
        except json.JSONDecodeError:
            print(f"  !! unreadable {rep}")
            continue
        for o in data.get("objects", []):
            o = dict(o)
            o["scene"] = scene
            lab = (o.get("label") or "?").strip().lower()
            o["cat"] = ALIAS.get(lab, lab)
            rows.append(o)
    return rows


def pooled_f1(objs, key="f1_20"):
    v = [o[key] for o in objs if o.get(key) is not None]
    return float(np.mean(v)) if v else float("nan")


def load_drop_v2(root: Path, suffix="_factory"):
    """Corrected drop test (link frame) -> {(scene, obj_name): row}.

    report.json still carries the ORIGINAL drop test, which measured drift in
    PyBullet's COM frame and was run on pre-hybrid assets; redrop.py replays it
    in the canonical link frame and writes drop_v2.json. Always prefer the
    latter -- the two differ by ~3 points of stability.
    """
    out = {}
    for p in sorted(root.glob(f"*{suffix}/drop_v2.json")):
        scene = p.parent.name.replace(suffix, "")
        try:
            d = json.loads(p.read_text())
        except json.JSONDecodeError:
            continue
        for r in d.get("objects", []):
            out[(scene, r["name"])] = r
    return out


# --------------------------------------------------------------- tables ----

def table_per_category(rows, out: Path):
    by = defaultdict(list)
    for o in rows:
        by[o["cat"]].append(o)
    big = {k: v for k, v in by.items() if len(v) >= MIN_CAT_N}
    small = [o for k, v in by.items() if len(v) < MIN_CAT_N for o in v]
    order = sorted(big, key=lambda k: -len(big[k]))

    def row(name, objs):
        n = len(objs)
        ab = [o for o in objs if o.get("tier") in ("A", "B")]
        tested = [o for o in objs if o.get("drop") is not None]
        stable = [o for o in tested if o["drop"].get("stable")]
        f1 = pooled_f1(ab)
        f1s = f"{f1:.3f}" if f1 == f1 else "--"
        st = f"{100 * len(stable) / len(tested):.0f}\\%" if tested else "--"
        return (f"{esc(name)} & {n} & {100 * len(ab) / max(n, 1):.0f}\\% & "
                f"{f1s} & {st} \\\\")

    lines = [r"% generated by agents.eval.make_paper_tables -- do not edit",
             r"\begin{tabular}{lrrrr}", r"\toprule",
             r"category & $n$ & yield & F1@20 & stable \\", r"\midrule"]
    lines += [row(k, big[k]) for k in order]
    if small:
        ncat = len({o["cat"] for o in small})
        lines += [r"\midrule", row(f"other ({ncat} categories)", small)]
    lines += [r"\midrule", row("all", rows), r"\bottomrule", r"\end{tabular}"]
    (out / "per_category.tex").write_text("\n".join(lines) + "\n")
    print(f"  per_category.tex: {len(order)} named categories + other")


def table_stage_timing(summary, out: Path):
    st = summary["efficiency"]["stage_seconds_total"]
    total = sum(st.values())
    pretty = {
        "factory_prepare": "instance enumeration + best-view crop",
        "factory_refine_masks": "SAM3 mask evidence",
        "s4 TRELLIS image-to-3D": "asset generation (TRELLIS)",
        "factory_align": "registration",
        "s6 CoACD + physics annotation + URDF": "collision + physics + URDF",
        "factory_report": "drop test + report",
        "factory_eval_render": "render metrics",
    }
    lines = [r"% generated by agents.eval.make_paper_tables -- do not edit",
             r"\begin{tabular}{lrr}", r"\toprule",
             r"stage & A6000-h & share \\", r"\midrule"]
    for k, s in sorted(st.items(), key=lambda kv: -kv[1]):
        lines.append(f"{esc(pretty.get(k, k))} & {s / 3600:.2f} & "
                     f"{100 * s / max(total, 1):.0f}\\% \\\\")
    lines += [r"\midrule", f"total & {total / 3600:.2f} & 100\\% \\\\",
              r"\bottomrule", r"\end{tabular}"]
    (out / "stage_timing.tex").write_text("\n".join(lines) + "\n")
    print(f"  stage_timing.tex: {total / 3600:.2f} A6000-h over {len(st)} stages")


def table_per_scene(summary, out: Path):
    """Two side-by-side tabulars: longtable cannot be used in two-column mode,
    and 50 rows split in half fits one full-width float."""
    scenes = sorted(summary["per_scene"], key=lambda r: r["scene"])

    def body(rows):
        acc = []
        for s in rows:
            f1 = s.get("f1_20")
            bg = (s.get("bg") or {}).get("psnr")
            tw = (s.get("twin") or {}).get("psnr")
            f1s = f"{f1:.3f}" if isinstance(f1, float) and f1 == f1 else "--"
            sts = f"{s['stable']}/{s['tested']}" if s.get("tested") else "--"
            rnd = f"{bg:.1f}/{tw:.1f}" if bg and tw else "--"
            acc.append(f"\\texttt{{{s['scene']}}} & {s['n']} & {s['A']} & "
                       f"{s['B']} & {f1s} & {sts} & {rnd} & "
                       f"{s['time_s'] / 60:.0f} \\\\")
        return acc

    head = [r"\begin{tabular}{lrrrrrrr}", r"\toprule",
            r"scene & $n$ & A & B & F1@20 & stab. & bg/twin & min \\",
            r"\midrule"]
    tail = [r"\bottomrule", r"\end{tabular}"]
    half = (len(scenes) + 1) // 2
    lines = ([r"% generated by agents.eval.make_paper_tables -- do not edit"]
             + head + body(scenes[:half]) + tail
             + [r"\hfill"]
             + head + body(scenes[half:]) + tail)
    (out / "per_scene.tex").write_text("\n".join(lines) + "\n")
    print(f"  per_scene.tex: {len(scenes)} scenes (2 x {half})")


def table_hybrid(root: Path, out: Path):
    """Per-category TRELLIS vs ReconViaGen win rates from hybrid_all.json."""
    by = defaultdict(lambda: {"n": 0, "rvg": 0, "t": [], "r": [], "coll": 0})
    for hp in sorted(root.glob("*_factory/objects/hybrid_all.json")):
        try:
            rows = json.loads(hp.read_text()).get("rows", [])
        except json.JSONDecodeError:
            continue
        for r in rows:
            tr, rv = r.get("trellis") or {}, r.get("rvg") or {}
            ft, fr = tr.get("f1_20"), rv.get("f1_20")
            if ft is None or fr is None:
                continue
            lab = (r.get("label") or "?").strip().lower()
            c = by[ALIAS.get(lab, lab)]
            c["n"] += 1
            c["t"].append(ft)
            c["r"].append(fr)
            if str(r.get("winner", "")).lower().startswith("rvg"):
                c["rvg"] += 1
            if fr < 0.1:
                c["coll"] += 1
    if not by:
        print("  hybrid: no dual-scored rows found, skipping")
        return
    order = sorted((k for k in by if by[k]["n"] >= 4), key=lambda k: -by[k]["n"])
    lines = [r"% generated by agents.eval.make_paper_tables -- do not edit",
             r"\begin{tabular}{lrrrrr}", r"\toprule",
             r"category & $n$ & TRELLIS & RVG & RVG chosen & collapses \\",
             r"\midrule"]
    for k in order:
        c = by[k]
        lines.append(f"{esc(k)} & {c['n']} & {np.mean(c['t']):.3f} & "
                     f"{np.mean(c['r']):.3f} & "
                     f"{100 * c['rvg'] / c['n']:.0f}\\% & {c['coll']} \\\\")
    tot_n = sum(c["n"] for c in by.values())
    tot_rvg = sum(c["rvg"] for c in by.values())
    tot_coll = sum(c["coll"] for c in by.values())
    all_t = [x for c in by.values() for x in c["t"]]
    all_r = [x for c in by.values() for x in c["r"]]
    lines += [r"\midrule",
              f"all & {tot_n} & {np.mean(all_t):.3f} & {np.mean(all_r):.3f} & "
              f"{100 * tot_rvg / max(tot_n, 1):.0f}\\% & {tot_coll} \\\\",
              r"\bottomrule", r"\end{tabular}"]
    (out / "hybrid_per_category.tex").write_text("\n".join(lines) + "\n")
    print(f"  hybrid_per_category.tex: {tot_n} dual-scored objects, "
          f"{tot_coll} collapses")


def table_sr_sweep(root: Path, out: Path):
    """Stability ratio vs the drift threshold, measured, both modes.

    The 3 cm / 2 s criterion is a convention, and the two published protocols
    disagree by >50 points on a shared baseline, so we publish the curve.
    Also reports how many objects the COM->link frame fix reclassifies.
    """
    THRESH = [0.01, 0.02, 0.03, 0.05, 0.10]
    cols = []
    for suffix, label in (("_factory", "GT-driven"), ("_auto", "automatic")):
        rows = list(load_drop_v2(root, suffix).values())
        if not rows:
            continue
        d = np.array([r["drift_m"] for r in rows], dtype=float)
        sunk = np.array([bool(r.get("sunk")) for r in rows])
        raw = np.array([r.get("drift_raw_m", np.nan) for r in rows], dtype=float)
        sr = [100 * float(((d < t) & ~sunk).mean()) for t in THRESH]
        # objects whose 3cm classification flips between COM and link frames
        ok = ~np.isnan(raw)
        flips = int((((d[ok] < 0.03) & ~sunk[ok])
                     != ((raw[ok] < 0.03) & ~sunk[ok])).sum())
        cols.append((label, len(rows), sr, flips,
                     (float(np.median(d)), float(np.percentile(d, 90)))))
    if not cols:
        print("  sr_sweep: no drop_v2.json found, skipping")
        return
    lines = [r"% generated by agents.eval.make_paper_tables -- do not edit",
             r"\begin{tabular}{lr" + "r" * len(THRESH) + r"r}", r"\toprule",
             r"mode & $n$ & "
             + " & ".join(f"{int(t*100)}\\,cm" for t in THRESH)
             + r" & drift p50 / p90 \\", r"\midrule"]
    for label, n, sr, _flips, (p50, p90) in cols:
        lines.append(f"{label} & {n} & "
                     + " & ".join(f"{v:.1f}" for v in sr)
                     + f" & {p50*1000:.2f} / {p90*1000:.0f}\\,mm \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    (out / "sr_sweep.tex").write_text("\n".join(lines) + "\n")
    for label, n, sr, flips, (p50, p90) in cols:
        print(f"  sr_sweep {label}: n={n} SR@3cm={sr[2]:.1f}% "
              f"drift p50={p50*1000:.2f}mm p90={p90*1000:.0f}mm "
              f"(COM-vs-link reclassifies {flips})")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(C.ROOT / "docs" / "paper" / "tables"))
    ap.add_argument("--outputs", default=str(C.ROOT / "outputs"))
    a = ap.parse_args()

    out, root = Path(a.out), Path(a.outputs)
    out.mkdir(parents=True, exist_ok=True)

    summary = json.loads((root / "val_summary.json").read_text())
    rows = load_scene_objects(root)
    # attach the CORRECTED (link-frame, post-hybrid) drop test to each object
    drop = load_drop_v2(root)
    n_attached = 0
    for o in rows:
        r = drop.get((o["scene"], f"obj_{o['index']:02d}"))
        o["drop"] = r
        n_attached += r is not None
    print(f"[tables] {len(rows)} objects over "
          f"{len({r['scene'] for r in rows})} scenes -> {out}")
    print(f"[tables] corrected drop test attached to {n_attached} objects")

    table_per_category(rows, out)
    table_stage_timing(summary, out)
    table_per_scene(summary, out)
    table_hybrid(root, out)
    table_sr_sweep(root, out)


if __name__ == "__main__":
    main()
