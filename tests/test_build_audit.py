def test_cli_writes_audit_json_and_human_report(tmp_path):
    build_dir = tmp_path / "happy_path"
    shutil.copytree(FIXTURES / "happy_path", build_dir)
    proc = subprocess.run(
        [sys.executable, "-m", "agents.eval.build_audit", str(build_dir)],
        cwd=ROOT, capture_output=True, text=True,
    )
    assert proc.returncode == 0, proc.stdout + proc.stderr
    out_json = build_dir / "build_audit.json"
    out_md = build_dir / "build_audit_report.md"
    assert out_json.exists() and out_md.exists()
    written = json.loads(out_json.read_text())
    assert written["overall_status"] == ba.STATUS_PASS
    assert "Overall: PASS" in out_md.read_text()


