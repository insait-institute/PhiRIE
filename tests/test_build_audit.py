# --------------------------------------------------------------------------
# Mutation sanity: flipping evidence flips exactly the check it should.
# --------------------------------------------------------------------------

def test_flipping_trim_ok_flips_only_support_overlap(tmp_path):
    build_dir = tmp_path / "b"
    shutil.copytree(FIXTURES / "happy_path", build_dir)
    a_before = ba.run_audit(build_dir)
    assert a_before["checks"]["support_overlap"]["status"] == ba.STATUS_PASS

    plane_path = build_dir / "inpaint" / "obj_00" / "plane.json"
    plane = json.loads(plane_path.read_text())
    plane["trim_ok"] = False
    plane_path.write_text(json.dumps(plane))

    a_after = ba.run_audit(build_dir)
    assert a_after["checks"]["support_overlap"]["status"] == ba.STATUS_FAIL
    # nothing else should have moved
    for check_name in a_before["checks"]:
        if check_name == "support_overlap":
            continue
        assert a_before["checks"][check_name]["status"] == a_after["checks"][check_name]["status"], check_name
