def test_room_collision_and_alignment_checks_are_not_applicable_pending_upstream():
    """Task 06 (room_collision.py) and Task 04 (robot_align.py /
    alignment_report.py) have not landed yet -- every fixture must expose
    these four + two checks as not_applicable with a reason naming the
    pending task, never fail (no evidence to fail on) and never pass."""
    for name in ALL_FIXTURES:
        a = audit(name)
        for check_name in ("room_collision_coverage", "room_disconnected_components",
                           "room_penetration_max", "room_settle_drift"):
            res = a["checks"][check_name]
            assert res["status"] == ba.STATUS_NA
            assert "Task 06" in res["reason"]
        for check_name in ("metric_scale", "robot_alignment"):
            res = a["checks"][check_name]
            assert res["status"] == ba.STATUS_NA
            assert "Task 04" in res["reason"]


